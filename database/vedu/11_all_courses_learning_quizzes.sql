\set ON_ERROR_STOP on

BEGIN;

-- Standardize the informational opening section for all 21 curated courses.
-- It is deliberately not a required learning module and never contains a quiz.
UPDATE lms.course_sections s
SET title = 'Giới thiệu môn học',
    module_type = 'INTRO',
    is_required = false,
    outcomes = '[]'::jsonb
FROM lms.curated_courses cc
WHERE cc.course_id = s.course_id
  AND s.module_key = 'intro';

UPDATE lms.lessons l
SET title = 'Giới thiệu môn học',
    content = 'Chào mừng bạn đã đến với khóa học của VEDU! Hãy tiếp tục hành trình học tập.',
    estimated_duration_seconds = 0,
    updated_at = now()
FROM lms.course_sections s
JOIN lms.curated_courses cc ON cc.course_id = s.course_id
WHERE l.section_id = s.section_id
  AND s.module_key = 'intro'
  AND l.is_published
  AND NOT l.is_deleted;

UPDATE assessment.quizzes q
SET is_published = false,
    updated_at = now()
FROM lms.lessons l
JOIN lms.course_sections s ON s.section_id = l.section_id
JOIN lms.curated_courses cc ON cc.course_id = s.course_id
WHERE q.lesson_id = l.lesson_id
  AND s.module_key = 'intro'
  AND q.is_published
  AND NOT q.is_deleted;

-- Every content module contributes to completion. The opening section above does not.
UPDATE lms.course_sections s
SET is_required = true
FROM lms.curated_courses cc
WHERE cc.course_id = s.course_id
  AND s.module_key <> 'intro';

-- The five office/digital-skills courses use quizzes only: lesson quizzes plus one
-- final MCQ exam. Existing submissions are retained; assignments are only archived.
UPDATE lms.courses c
SET learning_type = 'SKILL_BASED',
    final_mode = 'MCQ_ONLY',
    updated_at = now()
FROM lms.curated_courses cc
WHERE cc.course_id = c.course_id
  AND cc.course_key IN ('word','excel','powerpoint','digital','digital-literacy');

UPDATE assessment.course_assignments a
SET is_published = false,
    is_archived = true,
    updated_at = now()
FROM lms.curated_courses cc
WHERE cc.course_id = a.course_id
  AND cc.course_key IN ('word','excel','powerpoint','digital','digital-literacy')
  AND (a.is_published OR NOT a.is_archived);

WITH selected_final AS (
  SELECT cc.course_id, max(q.quiz_id) AS quiz_id
  FROM lms.curated_courses cc
  JOIN assessment.quizzes q ON q.course_id = cc.course_id
  WHERE cc.course_key IN ('word','excel','powerpoint','digital','digital-literacy')
    AND q.lesson_id IS NULL
    AND NOT q.is_deleted
  GROUP BY cc.course_id
)
UPDATE assessment.quizzes q
SET is_published = (q.quiz_id = selected_final.quiz_id),
    passing_score = CASE WHEN q.quiz_id = selected_final.quiz_id THEN 7 ELSE q.passing_score END,
    max_attempts = CASE WHEN q.quiz_id = selected_final.quiz_id THEN 3 ELSE q.max_attempts END,
    updated_at = now()
FROM selected_final
WHERE q.course_id = selected_final.course_id
  AND q.lesson_id IS NULL
  AND NOT q.is_deleted;

-- Create a three-question quiz for every content lesson that does not have one.
-- Questions and answers are copied from that course's existing reviewed final bank;
-- no new academic statement is generated by this migration.
DO $lesson_quizzes$
DECLARE
  target record;
  source_question record;
  source_answer record;
  final_quiz_id bigint;
  created_quiz_id bigint;
  created_question_id bigint;
  source_question_count integer;
  source_offset integer;
  quiz_question_order integer;
BEGIN
  FOR target IN
    SELECT cc.course_key,
           l.course_id,
           l.lesson_id,
           l.lesson_order,
           l.title AS lesson_title
    FROM lms.curated_courses cc
    JOIN lms.lessons l ON l.course_id = cc.course_id
    JOIN lms.course_sections s ON s.section_id = l.section_id
    WHERE cc.course_key <> 'oop'
      AND s.module_key <> 'intro'
      AND l.is_published
      AND NOT l.is_deleted
    ORDER BY cc.course_key, l.lesson_order, l.lesson_id
  LOOP
    IF EXISTS (
      SELECT 1
      FROM assessment.quizzes q
      WHERE q.lesson_id = target.lesson_id
        AND q.is_published
        AND NOT q.is_deleted
    ) THEN
      CONTINUE;
    END IF;

    SELECT q.quiz_id
    INTO final_quiz_id
    FROM assessment.quizzes q
    WHERE q.course_id = target.course_id
      AND q.lesson_id IS NULL
      AND q.is_published
      AND NOT q.is_deleted
    ORDER BY q.quiz_id DESC
    LIMIT 1;

    IF final_quiz_id IS NULL THEN
      RAISE EXCEPTION 'Course % has no published final quiz bank', target.course_key;
    END IF;

    SELECT count(*)::integer
    INTO source_question_count
    FROM assessment.questions
    WHERE quiz_id = final_quiz_id;

    IF source_question_count < 1 THEN
      RAISE EXCEPTION 'Final quiz % for course % has no questions', final_quiz_id, target.course_key;
    END IF;

    INSERT INTO assessment.quizzes(
      course_id, lesson_id, title, description, time_limit_seconds,
      passing_score, max_attempts, is_published
    ) VALUES (
      target.course_id,
      target.lesson_id,
      'Quiz cuối bài — ' || regexp_replace(target.lesson_title, '^\s*[0-9]+\s*[.·:-]*\s*', ''),
      '[VEDU-LESSON-QUIZ-V1] Câu hỏi được chọn từ ngân hàng đã duyệt của khóa học.',
      420,
      7,
      3,
      true
    ) RETURNING quiz_id INTO created_quiz_id;

    FOR quiz_question_order IN 1..LEAST(3, source_question_count) LOOP
      source_offset := mod((target.lesson_order - 2) * 3 + quiz_question_order - 1, source_question_count);

      SELECT q.question_id, q.question_text, q.question_type, q.points
      INTO source_question
      FROM assessment.questions q
      WHERE q.quiz_id = final_quiz_id
      ORDER BY q.question_order, q.question_id
      OFFSET source_offset
      LIMIT 1;

      INSERT INTO assessment.questions(
        quiz_id, question_text, question_type, question_order, points
      ) VALUES (
        created_quiz_id,
        source_question.question_text,
        source_question.question_type,
        quiz_question_order,
        source_question.points
      ) RETURNING question_id INTO created_question_id;

      FOR source_answer IN
        SELECT answer_text, is_correct, answer_order
        FROM assessment.answers
        WHERE question_id = source_question.question_id
        ORDER BY answer_order, answer_id
      LOOP
        INSERT INTO assessment.answers(question_id, answer_text, is_correct, answer_order)
        VALUES(
          created_question_id,
          source_answer.answer_text,
          source_answer.is_correct,
          source_answer.answer_order
        );
      END LOOP;

      INSERT INTO assessment.question_skills(question_id, skill)
      SELECT created_question_id, skill
      FROM assessment.question_skills
      WHERE question_id = source_question.question_id
      ON CONFLICT(question_id) DO NOTHING;
    END LOOP;
  END LOOP;
END $lesson_quizzes$;

-- Apply the same attempt/pass policy to every generated lesson quiz when rerun.
UPDATE assessment.quizzes q
SET passing_score = 7,
    max_attempts = 3,
    time_limit_seconds = 420,
    updated_at = now()
WHERE q.description LIKE '[VEDU-LESSON-QUIZ-V1]%'
  AND NOT q.is_deleted;

UPDATE lms.course_overviews o
SET practice_note = CASE
  WHEN cc.course_key IN ('word','excel','powerpoint','digital','digital-literacy')
    THEN 'Mỗi bài có quiz củng cố. Hoàn thành các module bắt buộc và đạt bài kiểm tra cuối khóa để đủ điều kiện chứng nhận.'
  ELSE 'Học theo từng module, làm quiz cuối bài và hoàn thành đánh giá cuối khóa theo yêu cầu của khóa học.'
END
FROM lms.curated_courses cc
WHERE cc.course_id = o.course_id;

COMMIT;
